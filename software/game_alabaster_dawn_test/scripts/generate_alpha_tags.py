#!/usr/bin/env python3
"""Build conservative normal-bullet/laser spatial tags; no schedule simulation."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
STATE = struct.Struct('<hhHHHHHHHH')
EVENT = struct.Struct('<IIIhhhhBBBB')
END = 0x8000
MAP_TOP = 50
MAX_WIDTH = 24


def overlap(a, b):
    """Half-open integer rectangles, in map-local coordinates."""
    return a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]


def bullet_rect(r):
    # Render's normal cache sprite is 18x18 centred on (raw x+9,raw y+9).
    # Clip to the map, never use source-clipped dimensions as an origin.
    return (max(0, r[0]), max(0, r[1]-MAP_TOP),
            min(1280, r[0]+18), min(630, r[1]-MAP_TOP+18))


def laser_rect(event, width):
    x, y, ex = event[3:6]
    return (min(x, ex), y-MAP_TOP-width//2,
            max(x, ex)+1, y-MAP_TOP-width//2+width)


def build(source, effects_source=None):
    effects_source = effects_source or (source if (source/'effects').is_dir() else ROOT/'resources/source')
    paths = [source/'projectiles/trajectory_index.json',
             source/'projectiles/states_30hz.bin',
             effects_source/'effects/laser_events_60hz.bin',
             effects_source/'effects/laser_width_alpha_60hz.bin']
    index = json.loads(paths[0].read_text(encoding='utf-8'))
    raw = paths[1].read_bytes()
    events = list(EVENT.iter_unpack(paths[2].read_bytes()))
    widths = [r[0] for r in struct.iter_unpack('<HBB', paths[3].read_bytes())]
    if len(index) != 64 or len(events) != 8 or len(widths) != 180:
        raise ValueError('expected 64 trajectories, 8 beams and 180 width samples')
    if min(widths) < 0 or max(widths) != MAX_WIDTH:
        raise ValueError('width LUT no longer has maximum 24')
    if any(e[4] != e[6] for e in events):
        raise ValueError('only horizontal source beams supported')
    data = bytearray()
    entries = []
    for tid, t in enumerate(index):
        first, count = len(data), t['live_records']
        if t['id'] != tid or first != t['state_record_offset']:
            raise ValueError('source offsets must match generated first+age packing')
        entries.append({'id': tid, 'first': first, 'count': count})
        for age in range(count+1):
            r = STATE.unpack_from(raw, (t['state_record_offset']+age)*STATE.size)
            if bool(r[8] & END) != (age == count):
                raise ValueError(f'trajectory {tid} age {age}: bad END boundary')
            rect = bullet_rect(r)
            mask = 0
            if age != count and r[8] & 1 and rect[0] < rect[2] and rect[1] < rect[3]:
                for slot, event in enumerate(events):
                    if overlap(rect, laser_rect(event, MAX_WIDTH)):
                        mask |= 1 << slot
            data.append(mask)
    expected = sum(t['live_records']+1 for t in index)
    if len(raw) != expected*STATE.size or len(data) != expected:
        raise ValueError('source record layout differs from sum(live_records)+64 END')
    report = {'format': 'alpha_near_mask_u8_v1', 'bytes': len(data),
              'live_samples': len(data)-64, 'end_samples': 64,
              'max_laser_width': MAX_WIDTH, 'coordinate_system': 'map local, screen_y-50',
              'trajectory_index': entries,
              'tag_sha256': hashlib.sha256(data).hexdigest(),
              'zlib_bytes_informational': len(zlib.compress(data, 9)),
              'source_sha256': {(p.relative_to(source).as_posix() if p.is_relative_to(source) else p.relative_to(effects_source).as_posix()): hashlib.sha256(p.read_bytes()).hexdigest() for p in paths},
              'nonzero_samples': sum(bool(v) for v in data),
              'schedule_precomputed': False}
    return bytes(data), report


def verify_assets(path, entries):
    text = path.read_text(encoding='utf-8')
    match = re.search(r'asset_trajs\s*\[64\]\s*=\s*\{(.*?)\};', text, re.S)
    if not match:
        raise ValueError('cannot find generated asset_trajs[64]')
    rows = [tuple(map(int, r)) for r in re.findall(r'\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}', match[1])]
    if rows != [(e['first'], e['count'], 0) for e in entries]:
        raise ValueError('asset_trajs first/count differ from precomputed tags')


def emit_header(data):
    values = '\n'.join('    '+','.join(f'0x{x:02x}' for x in data[i:i+32])+',' for i in range(0,len(data),32))
    return '''/* Generated by scripts/generate_alpha_tags.py. Do not edit.
 * Define ALPHA_TAGS_IMPLEMENTATION in ONE translation unit before including.
 * Spatial necessary condition ONLY: gate active phase/slot and actual width.
 * Ordinary 18x18 bullets only; not yellow effects or dynamic player overlap. */
#ifndef G24_ALPHA_TAGS_H
#define G24_ALPHA_TAGS_H
#include <stdint.h>
#define ALPHA_TAGS_POINT_COUNT '''+str(len(data))+'''u
#define ALPHA_TAGS_MAX_LASER_WIDTH 24u
#ifdef __cplusplus
extern "C" {
#endif
extern const uint8_t alpha_laser_near_mask[ALPHA_TAGS_POINT_COUNT];
#ifdef ALPHA_TAGS_IMPLEMENTATION
const uint8_t alpha_laser_near_mask[ALPHA_TAGS_POINT_COUNT] = {
'''+values+'''
};
#endif
/* first is asset_trajs[traj].first; age is that instance's current 30Hz age.
 * count excludes END; out of range and END cannot leak a neighbouring tag. */
static inline uint8_t alpha_tags_mask(uint32_t point_index) {
    return point_index < ALPHA_TAGS_POINT_COUNT ? alpha_laser_near_mask[point_index] : 0u;
}
static inline uint8_t alpha_tags_for_age(uint32_t first, uint32_t age, uint32_t count) {
    return age < count && first < ALPHA_TAGS_POINT_COUNT &&
           age < ALPHA_TAGS_POINT_COUNT-first ? alpha_tags_mask(first+age) : 0u;
}
/* Caller supplies the CURRENT active LaserIndex slot (not trajectory phase). */
static inline int alpha_tags_near_slot(uint8_t mask, unsigned active_slot) {
    return active_slot < 8u && (mask & (uint8_t)(1u << active_slot)) != 0u;
}
#ifdef __cplusplus
}
#endif
#endif
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT/'resources/speed_1p2')
    parser.add_argument('--effects-source', type=Path, default=ROOT/'resources/source')
    parser.add_argument('--output-root', type=Path, default=ROOT)
    parser.add_argument('--verify-assets', type=Path, default=ROOT/'src/assets_generated.c')
    parser.add_argument('--check', action='store_true', help='verify outputs without writing')
    args = parser.parse_args()
    data, report = build(args.source, args.effects_source)
    verify_assets(args.verify_assets, report['trajectory_index'])
    report['asset_first_count_verified'] = True
    outputs = {args.output_root/'src/alpha_tags.h': emit_header(data).encode(),
               args.output_root/'resources/alpha_tags/laser_near_mask.bin': data,
               args.output_root/'resources/alpha_tags/manifest.json': (json.dumps(report, indent=2)+'\n').encode()}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                raise SystemExit(f'stale or missing output: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(f"{'Verified' if args.check else 'Generated'} {len(data)} bytes; {report['nonzero_samples']} nonzero; offsets verified")


if __name__ == '__main__':
    main()
