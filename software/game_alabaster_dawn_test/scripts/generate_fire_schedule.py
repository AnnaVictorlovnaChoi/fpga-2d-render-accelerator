"""Bake original Python binary64 30Hz timers; no target floats or replay wrap."""
import argparse
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / 'FPGA_Preprocessed_Final/data/projectiles'


def generate(frames=18000):
    timing = SOURCE / 'source/timing_v2.json'
    turrets = json.loads(timing.read_text(encoding='utf-8'))['turrets']
    timers = [0.0] * 16
    masks = []
    events = []
    directions = [0] * 16
    for frame in range(frames):
        mask = 0
        for i, t in enumerate(turrets):
            timers[i] -= 1.0 / 30
            if timers[i] <= 0:
                timers[i] += t['interval_s']
                mask |= 1 << i
                if frame < 9000:
                    events.append((frame, i * 4 + directions[i] % 4))
                directions[i] += 1
        masks.append(mask)
    reference = (SOURCE / 'reference_events_300s.bin').read_bytes()
    assert b''.join(struct.pack('<HH', *e) for e in events) == reference
    # At the boundary timers describe remaining time AFTER frame frames-1.
    # Rational fallback uses 1/3000s units, preserving the residual rather than restarting.
    intervals = [round(t['interval_s'] * 3000) for t in turrets]
    remaining = [round(t * 3000) for t in timers]
    blob = struct.pack('<' + 'H' * len(masks), *masks)
    hashes = {str(p.relative_to(SOURCE)): hashlib.sha256(p.read_bytes()).hexdigest()
              for p in (timing, SOURCE / 'source/barrage_demo.py', SOURCE / 'reference_events_300s.bin')}
    metadata = {'frames': frames, 'hz': 30, 'bytes': len(blob), 'sha256': hashlib.sha256(blob).hexdigest(),
                'sources_sha256': hashes, 'fallback_units_per_second': 3000,
                'fallback_remaining': remaining, 'fallback_intervals': intervals,
                'fallback_note': 'After table: rational integer timers; residual phase retained; binary64 boundary rounding may differ by one frame.'}
    return masks, blob, metadata


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    masks, blob, metadata = generate()
    header = ('/* Generated by scripts/generate_fire_schedule.py; do not edit. */\n'
              '#ifndef G24_FIRE_SCHEDULE_H\n#define G24_FIRE_SCHEDULE_H\n#include <stdint.h>\n'
              f'#define FIRE_SCHEDULE_FRAMES {len(masks)}u\n'
              'static const uint16_t fire_schedule[FIRE_SCHEDULE_FRAMES]={\n')
    header += ''.join(' ' + ','.join(f'0x{x:04x}' for x in masks[i:i+16]) + ',\n' for i in range(0, len(masks), 16))
    header += '};\nstatic const uint16_t fire_interval_units[16]={' + ','.join(map(str, metadata['fallback_intervals'])) + '};\n'
    header += 'static const int32_t fire_tail_units[16]={' + ','.join(map(str, metadata['fallback_remaining'])) + '};\n#endif\n'
    outputs = {ROOT / 'src/fire_schedule.h': header.encode(), ROOT / 'resources/fire_schedule/masks_30hz_600s.bin': blob,
               ROOT / 'resources/fire_schedule/manifest.json': (json.dumps(metadata, indent=2) + '\n').encode()}
    for path, data in outputs.items():
        if args.check:
            assert path.read_bytes() == data, f'stale generated file: {path}'
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f'fire schedule: {len(masks)} frames, {len(blob)} bytes; 300s reference events identical')


if __name__ == '__main__':
    main()
