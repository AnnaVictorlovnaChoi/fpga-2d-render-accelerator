"""Generate exact-time accelerators; source frame end_us remains authoritative.
4096us buckets contain at most one transition; runtime checks that exact boundary.
No image bytes, routes, or dragon timeline are generated or changed.
"""
from pathlib import Path
import bisect
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SHIFT = 12
STEP = 1 << SHIFT


def generate():
    source = ROOT / 'resources/player/fpga_player.h'
    text = source.read_text(encoding='utf-8')
    groups = re.findall(r'static const FpgaPlayerGroup (\w+) =', text)
    assert len(groups) == 38
    frames = {}
    for name, body in re.findall(r'static const FpgaPlayerFrame (\w+)_frames\[\] = \{(.*?)\n\};', text, re.S):
        frames[name] = [list(map(int, row.split(','))) for row in re.findall(r'\{([^{}]+)\}', body)]
    schedules = re.findall(r'static const int32_t (fpga_dodge_\w+)_schedule\[\]\[5\] = .*?\{(.*?)\n\};', text, re.S)
    dodge = None
    for _, body in schedules:
        rows = [list(map(int, row.split(','))) for row in re.findall(r'\{([^{}]+)\}', body)]
        ends = [row[2] for row in rows]
        assert dodge is None or dodge == ends
        dodge = ends
    assert dodge is not None and len(dodge) == 16
    data, offsets, unique = [], [], {}
    schedules = [[row[-1] for row in frames[name]] for name in groups[2:34]] + [dodge]
    for ends in schedules:
        assert len(ends) < 256
        assert all(b > a for a, b in zip([0] + ends[:-1], ends))
        # Ensures runtime needs at most one exact-end correction.
        assert all(b - a >= STEP for a, b in zip(ends, ends[1:]))
        table = tuple(min(bisect.bisect_right(ends, t), len(ends) - 1) for t in range(0, ends[-1], STEP))
        if table not in unique:
            unique[table] = len(data)
            data.extend(table)
        offsets.append(unique[table])
    assert len(data) < 65536
    lines = ['/* Generated by scripts/generate_render_tables.py. Do not edit. */',
             '#ifndef AD_RENDER_TIME_TABLES_H', '#define AD_RENDER_TIME_TABLES_H',
             '#include <stdint.h>', f'#define RENDER_TIME_SHIFT {SHIFT}u',
             'static const uint16_t render_time_offsets[33] = {' + ','.join(map(str, offsets)) + '};',
             f'static const uint8_t render_time_indices[{len(data)}] = {{']
    lines += [','.join(map(str, data[i:i+32])) + ',' for i in range(0, len(data), 32)]
    lines += ['};', '#endif', '']
    out = ROOT / 'resources/render_tables'
    out.mkdir(parents=True, exist_ok=True)
    (out / 'render_time_tables.h').write_text('\n'.join(lines), encoding='utf-8')
    report = {'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(), 'bucket_us': STEP,
              'index_bytes': len(data), 'offset_bytes': len(offsets) * 2,
              'unique_schedules': len(unique), 'max_boundary_corrections': 1,
              'time_rounding_us': 0}
    (out / 'manifest.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report))


if __name__ == '__main__':
    generate()
