#!/usr/bin/env python3
"""Generate immutable CPU command metadata, never change source pixels.
Usage: python scripts/generate_command_templates.py --output <temporary directory>
Copy verified outputs to resources/command_templates for final consumption.
"""
import argparse, hashlib, json, pathlib, struct
ROOT = pathlib.Path(__file__).resolve().parents[1]
def generate(payload):
    h = struct.unpack_from('<16I', payload)
    assert h[0] == 0x374e4545 and h[2] == len(payload) and h[5] == 7
    entries, ranges = [], []
    for fi in range(7):
        f = struct.unpack_from('<4H2i3IH2B', payload, h[9]+32*fi)
        first, count = f[6:8]
        frame_ranges=[]
        for alpha in (11,16,32):
            start=len(entries)
            for i in range(count):
                off,w,ht,x,y,a=struct.unpack_from('<I4HB',payload,h[10]+16*(first+i))
                effective=(a*alpha+16)>>5
                assert w<=24 and ht<=24 and x+w<=f[0] and y+ht<=f[1]
                assert off>=h[14] and off+2*w*ht<=len(payload)
                if effective: entries.append((off,y*1280+x,w,ht,i,effective,0 if effective==32 else effective,2 if effective==32 else 5))
            frame_ranges.append((start,len(entries)-start))
        ranges.append(frame_ranges)
    text='/* Generated by scripts/generate_command_templates.py; metadata only. */\n'
    text+='#define RENDER_TEMPLATE_PAYLOAD_BYTES %du\n'%len(payload)
    text+='static const RenderTemplateOp render_template_ops[]={\n'
    text+=''.join('{%du,%du,%d,%d,%d,%d,%d,%d},\n'%v for v in entries)+'};\n'
    text+='static const RenderTemplateRange render_template_ranges[7][3]={\n'
    text+=''.join('{'+','.join('{%d,%d}'%v for v in row)+'},\n' for row in ranges)+'};\n'
    return text, len(entries)
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--output',required=True);args=ap.parse_args()
    out=pathlib.Path(args.output);out.mkdir(parents=True,exist_ok=True)
    payload=(ROOT/'resources/enemy/payload.bin').read_bytes()
    text,count=generate(payload);blob=text.encode();(out/'enemy_commands.inc').write_bytes(blob)
    manifest={'schema':1,'stride_pixels':1280,'alpha_keys':[11,16,32],'entries':count,'payload_sha256':hashlib.sha256(payload).hexdigest(),'header_sha256':hashlib.sha256(blob).hexdigest(),'header_bytes':len(blob),'entry_c_bytes':16,'source_pixels_changed':False}
    (out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8');print(json.dumps(manifest))
if __name__=='__main__': main()
