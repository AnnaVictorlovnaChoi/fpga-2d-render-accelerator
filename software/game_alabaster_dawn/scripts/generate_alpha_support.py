#!/usr/bin/env python3
"""Build keyed RGB565 support from project packed payloads; stdlib only.
No source artwork, Pillow, runtime pixel reads, resource repacking, or new kind.
Usage: python scripts/generate_alpha_support.py --output-dir <staging directory>
Copy the two generated files into resources/alpha_support after verification.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import zlib


def sha(data):
    return hashlib.sha256(data).hexdigest()


def generate(root, output):
    output.mkdir(parents=True, exist_ok=True)
    lines = ['/* Generated by generate_alpha_support.py; key0 transparent. */',
             '#ifndef ALPHA_SUPPORT_TABLES_H', '#define ALPHA_SUPPORT_TABLES_H', '#include <stdint.h>']
    report = {'schema': 1, 'semantics': 'per-plane RGB565 != 0; SPRITE/ALPHASPRITE only; NOT unkeyed ALPHA/COPY', 'sources': {}, 'table_bytes': 0}
    def array(ctype, name, values):
        lines.append('static const %s %s[%d] = {' % (ctype, name, len(values)))
        for start in range(0, len(values), 16):
            lines.append(' ' + ','.join(str(v)+'u' for v in values[start:start+16]) + ',')
        lines.append('};')
    for name in ('dragon', 'flow'):
        directory = root / 'resources' / name
        layout_bytes = (directory / 'layout.h').read_bytes()
        layout = {k: int(v) for k, v in re.findall(r'#define\s+'+name.upper()+r'_(\w+)\s+(\d+)u', layout_bytes.decode())}
        streams_bytes = (directory / 'external_streams.json').read_bytes()
        stream = next(s for s in json.loads(streams_bytes)['streams'] if s['id'] == 0)
        assert stream['codec'] == 1 and stream['predictor'] == 0
        packed = (root / stream['path']).read_bytes()
        raw = zlib.decompress(packed, -15)
        assert len(raw) == layout['PAYLOAD_BYTES'] == stream['raw_bytes']
        assert sha(raw) == stream['decoded_sha256']
        assert zlib.crc32(packed) == stream['packed_crc']
        assert zlib.crc32(raw) == stream['raw_crc']
        assert struct.unpack_from('<I', raw, layout['FRAMES_OFFSET']+16)[0] == 0
        masks, mask_ids, sequences, runs, offsets = [], {}, {}, [], []
        for i in range(layout['TILES']):
            off, w, h, x, y, alpha = struct.unpack_from('<IHHHHB', raw, 16*i)
            assert 0 < w <= 24 and 0 < h <= 24 and 0 < alpha <= 32
            assert off % 2 == 0 and off+w*h*2 <= layout['RAW_BYTES']
            pixels = struct.unpack_from('<'+'H'*(w*h), raw, layout['META_BYTES']+off)
            rows = tuple(sum((pixels[yy*w+xx] != 0) << xx for xx in range(w)) for yy in range(h))
            if rows not in sequences:
                sequences[rows] = len(runs)
                yy = 0
                while yy < h:
                    value = rows[yy]
                    if value not in mask_ids:
                        mask_ids[value] = len(masks)
                        masks.append(value)
                    index = mask_ids[value]
                    assert index < 65536
                    end = yy+1
                    while end < h and rows[end] == value:
                        end += 1
                    runs.extend((index & 255, index >> 8, end))
                    yy = end
            offsets.append(sequences[rows])
        array('uint32_t', 'as_'+name+'_offsets', offsets)
        array('uint32_t', 'as_'+name+'_masks', masks)
        array('uint8_t', 'as_'+name+'_runs', runs)
        size = len(offsets)*4+len(masks)*4+len(runs)
        report['table_bytes'] += size
        report['sources'][name] = {'planes': len(offsets), 'unique_sequences': len(sequences), 'unique_masks': len(masks), 'run_bytes': len(runs), 'table_bytes': size,
            'packed_path': stream['path'], 'packed_sha256': sha(packed), 'decoded_sha256': sha(raw), 'metadata_sha256': sha(raw[:layout['META_BYTES']]),
            'layout_sha256': sha(layout_bytes), 'streams_sha256': sha(streams_bytes)}
    lines.append('#endif')
    header = ('\n'.join(lines)+'\n').encode()
    (output/'tables.h').write_bytes(header)
    report['tables_sha256'] = sha(header)
    assert report['table_bytes'] < 200000
    (output/'manifest.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--output-dir', type=Path, required=True)
    args = parser.parse_args()
    generate(args.root.resolve(), args.output_dir.resolve())
