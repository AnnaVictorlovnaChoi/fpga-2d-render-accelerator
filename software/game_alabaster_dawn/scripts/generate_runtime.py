"""Generate metadata wiring only; authoritative frames remain byte-identical snapshot."""
from pathlib import Path
import re,hashlib,json
root=Path(__file__).resolve().parents[1]
r=root/'resources/player'
h=(r/'fpga_player.h').read_text()
groups=re.findall(r'static const FpgaPlayerGroup (\w+) = \{(\d+),(\d+),(\d+),',h)
assert len(groups)==38
pack=(r/'player.pack').read_bytes()
assert len(pack)==1026337
out=['/* Generated by scripts/generate_runtime.py; do not hand edit. */','#include "runtime.h"']
out+=['const RuntimeGroup *const runtime_groups[] = {']+[f' &{g[0]},' for g in groups]+['};']
off=[]; n=0
for _,_,_,size in groups:
 n=(n+63)&~63;off.append(n);n+=int(size)
out+=['const uint32_t runtime_offsets[] = {'+','.join(map(str,off))+'};',f'const uint32_t runtime_raw_bytes={n}u;',f'const char runtime_source_sha256[]="{hashlib.sha256(pack).hexdigest()}";']
# All directional schedules have identical state/timing/scalar displacement.
schedules=re.findall(r'static const int32_t (fpga_dodge_\w+)_schedule\[\]\[5\] = .*?\{(.*?)\n\};',h,re.S)
rows=None
for name,body in schedules:
 rr=[list(map(int,x.split(','))) for x in re.findall(r'\{([^{}]+)\}',body)]
 scalar=[[a,b,c,abs(dx)+abs(dy)] for a,b,c,dx,dy in rr]
 assert len(scalar)==16
 if rows is not None: assert rows==scalar
 rows=scalar
assert rows[-1][-1]==165*256
out+=['const RuntimeDodgeStep runtime_dodge_steps[16] = {']+[' {'+','.join(map(str,x))+'},' for x in rows]+['};']
(root/'src/runtime_data.c').write_text('\n'.join(out)+'\n')
(root/'src/runtime_data.h').write_text(f'#define RUNTIME_ARENA_BYTES {n}u\n#define RUNTIME_PACK_BYTES {len(pack)}u\nextern const RuntimeGroup *const runtime_groups[38];\nextern const uint32_t runtime_offsets[38];\nextern const RuntimeDodgeStep runtime_dodge_steps[16];\n')
# Keep original S as immutable snapshot, with a project-root-relative build adapter.
(root/'src/runtime_blob.S').write_text((r/'fpga_player.S').read_text().replace('assets/player.pack','resources/player/player.pack'))
print(f'groups=38 arena={n} pack={len(pack)}')
